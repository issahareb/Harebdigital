import { chromium } from 'playwright'
import AxeBuilder from '@axe-core/playwright'
import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const base = process.env.SEO_BASE_URL || 'http://localhost:3002'
const output = process.env.QA_OUTPUT_DIR || '/tmp/hareb-landing-qa'
await fs.mkdir(output, {recursive:true})
const browser = await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE,args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu'],headless:true})
const consent = () => {
  localStorage.setItem('site-consent', JSON.stringify({version:4,decidedAt:new Date().toISOString(),analytics:false,lukas:false}))
  localStorage.setItem('hd-tiktok-consent-v1', JSON.stringify({allowed:false}))
}
const appearance = async page => page.locator('[data-track-id="offer-enquire-0"]').evaluate(el => {
  const css=getComputedStyle(el)
  return Object.fromEntries(['backgroundColor','color','borderRadius','fontFamily','fontSize','fontWeight','padding','minHeight','transition'].map(k=>[k,css[k]]))
})
for (const width of [320,390,768,1440]) {
  const context=await browser.newContext({viewport:{width,height:900},reducedMotion:'reduce'})
  await context.addInitScript(consent)
  const page=await context.newPage()
  const errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto(base+'/leistungen/neue-website/',{waitUntil:'networkidle'})
  await page.evaluate(()=>document.fonts.ready)
  assert.equal(await page.locator('h1').count(),1)
  assert.equal(await page.locator('link[rel="canonical"]').getAttribute('href'),'https://hareb.digital/leistungen/neue-website/')
  assert.equal(await page.locator('main img, main video').count(),0,'No separate hero image or film')
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No overflow')
  assert.equal(await page.getByRole('tab').count(),4)
  assert.ok((await page.getByRole('tablist').boundingBox()).y<900,'Choices are visible without scrolling')
  assert.equal(await page.locator('[data-track-id="website-main-site"]').getAttribute('href'),'/')
  const initial=await page.locator('main').innerText()
  assert.ok(initial.split(/\s+/).length<260,'Keep initial page copy concise')
  const landingAppearance=await appearance(page)
  const landingPanel=await page.getByRole('tabpanel').innerText()
  const home=await context.newPage()
  await home.goto(base+'/',{waitUntil:'domcontentloaded'})
  await home.locator('#angebote').scrollIntoViewIfNeeded()
  assert.deepEqual(await appearance(home),landingAppearance,'Use the exact homepage button styles')
  assert.equal(await home.getByRole('tabpanel').innerText(),landingPanel,'Use the exact homepage offer copy and layout')
  const homeHeading=await home.locator('#offer-title').evaluate(el=>{const s=getComputedStyle(el);return [s.fontSize,s.fontFamily,s.fontWeight,s.lineHeight,s.letterSpacing]})
  assert.deepEqual(await page.locator('#offer-title').evaluate(el=>{const s=getComputedStyle(el);return [s.fontSize,s.fontFamily,s.fontWeight,s.lineHeight,s.letterSpacing]}),homeHeading)
  await home.close()
  for(const [index,price,service] of [[0,'490','neue-website'],[1,'890','neue-website'],[2,'190','automatisierung'],[3,'590','neue-website']]) {
    await page.getByRole('tab').nth(index).click()
    assert.equal(await page.getByRole('tab').nth(index).getAttribute('aria-selected'),'true')
    assert.equal(await page.getByRole('tabpanel').count(),1)
    assert.ok((await page.getByRole('tabpanel').innerText()).includes(price+' €'))
    assert.equal(await page.locator(`[data-track-id="offer-enquire-${index}"]`).getAttribute('href'),`/kontakt/?leistung=${service}&angebot=${index}`)
  }
  await page.getByRole('tab').nth(0).focus()
  await page.keyboard.press('ArrowRight')
  assert.equal(await page.getByRole('tab').nth(1).getAttribute('aria-selected'),'true')
  await page.getByRole('button',{name:'Nächstes Angebot',exact:true}).click()
  assert.equal(await page.getByRole('tab').nth(2).getAttribute('aria-selected'),'true')
  await page.getByRole('button',{name:'Beispieltag 15',exact:true}).click()
  assert.ok((await page.getByRole('tabpanel').innerText()).includes('Tag 15'))
  await page.getByRole('tab').nth(0).click()
  const audit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()
  console.log(JSON.stringify({width,errors,violations:audit.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))}))}))
  assert.deepEqual(errors,[])
  assert.equal(audit.violations.length,0,'Accessibility audit')
  await page.evaluate(()=>{document.activeElement?.blur();scrollTo({top:0,behavior:'instant'})})
  await page.mouse.move(0,0)
  await page.screenshot({path:`${output}/${width}-hero.png`})
  await page.screenshot({path:`${output}/${width}-full.png`,fullPage:true})
  await page.locator('[data-track-id="offer-enquire-0"]').click()
  await page.waitForURL('**/kontakt/**')
  assert.equal(await page.locator('select[name="leistung"]').inputValue(),'neue-website')
  assert.match(await page.locator('textarea').inputValue(),/490/)
  await context.close()
}
const context=await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}})
const page=await context.newPage()
await page.goto(base+'/leistungen/neue-website/')
assert.ok(await page.locator('[data-track-id="offer-enquire-0"]').isVisible())
await browser.close()
console.log('Passed: exact homepage styling/copy, four choices, keyboard controls, demo, enquiry, responsive layouts and no-JS fallback.')
